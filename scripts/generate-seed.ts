/**
 * Generates supabase/seed.sql from src/content/seed.ts so the database starts
 * with exactly the same (verified or clearly provisional) content as the
 * fallback site. Run: npx tsx scripts/generate-seed.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import * as seed from "../src/content/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const e = seed.seedEdition;
const out: string[] = [
  "-- Generated by scripts/generate-seed.ts. Run on a fresh database, after the migrations. Each statement stands alone (it works in the Supabase SQL editor) and is safe to run again.",
  "begin;",
  `insert into public.editions (year, slug, name, theme, theme_statement, event_date, start_time, end_time, timezone, venue_name, venue_institution, venue_address, venue_notes, expected_attendance, status, registration_url, registration_note, event_day_mode, post_event_mode, is_current, highlights, host_institution, poster_deadline, poster_requirements, abstract_config)
values (${[e.year, e.slug, e.name, e.theme, e.themeStatement, e.date, e.startTime, e.endTime, e.timezone, e.venueName, e.venueInstitution, e.venueAddress, e.venueNotes, e.expectedAttendance, e.status, e.registrationUrl, e.registrationNote, e.eventDayMode, e.postEventMode, true, e.highlights, e.hostInstitution, e.posterDeadline, e.posterRequirements, e.abstractConfig].map(q).join(", ")})\non conflict (year) do nothing;`,
];

for (const [i, r] of seed.seedRooms.entries()) {
  out.push(`insert into public.rooms (edition_id, name, building, floor, directions, capacity, sort) select id, ${[r.name, r.building, r.floor, r.directions, r.capacity, i].map(q).join(", ")} from _ed where not exists (select 1 from public.rooms x where x.edition_id = _ed.id and x.name = ${q(r.name)});`);
}
for (const w of seed.seedWorkshops) {
  out.push(
    `insert into public.workshops (edition_id, slug, number, title, strapline, summary, description, topics, outcomes, audience, facilitator, facilitator_bio, capacity, booking_enabled, accent, motif, notes) select id, ${[w.slug, w.number, w.title, w.strapline, w.summary, w.description, w.topics, w.outcomes, w.audience, w.facilitator, w.facilitatorBio, w.capacity, w.bookingEnabled, w.accent, w.motif, w.notes].map(q).join(", ")} from _ed on conflict (edition_id, slug) do nothing;`,
  );
}
const roomName = new Map(seed.seedRooms.map((r) => [r.id, r.name]));
const sessionSql: string[] = [];
for (const s of seed.seedSessions) {
  const room = s.roomId ? `(select r.id from public.rooms r join _ed on r.edition_id = _ed.id where r.name = ${q(roomName.get(s.roomId))} limit 1)` : "null";
  sessionSql.push(
    `insert into public.sessions (edition_id, slug, title, category, starts_at, ends_at, room_id, description, objectives, capacity, is_provisional, sort) select id, ${[s.slug, s.title, s.category, s.startsAt, s.endsAt].map(q).join(", ")}, ${room}, ${[s.description, s.objectives, s.capacity, s.isProvisional, s.sort].map(q).join(", ")} from _ed on conflict (edition_id, slug) do nothing;`,
  );
}
out.push(...sessionSql);
const committeeSql = seed.seedCommittee.map(
  (c, i) =>
    `insert into public.committee_members (name, role, institution, bio, photo_url, links, published, sort) select ${[c.name, c.role, c.institution, c.bio, c.photoUrl].map(q).join(", ")}, ${q(JSON.stringify(c.links))}::jsonb, ${[true, i].map(q).join(", ")} where not exists (select 1 from public.committee_members where name = ${q(c.name)} and role = ${q(c.role)});`,
);
out.push(...committeeSql);
const placeSlug = new Map(seed.seedMapPlaces.map((p) => [p.id, p.slug]));
const placeSql = seed.seedMapPlaces.map((p, i) => {
  const parent = p.parentId ? `(select id from public.map_places where slug = ${q(placeSlug.get(p.parentId))})` : "null";
  const room = p.roomId ? `(select r.id from public.rooms r join _ed on r.edition_id = _ed.id where r.name = ${q(roomName.get(p.roomId))} limit 1)` : "null";
  return `insert into public.map_places (slug, name, code, kind, description, lat, lng, parent_id, room_id, directions, location_confirmed, published, sort) select ${[p.slug, p.name, p.code, p.kind, p.description, p.lat, p.lng].map(q).join(", ")}, ${parent}, ${room}, ${[p.directions, p.locationConfirmed, true, i].map(q).join(", ")} from _ed on conflict (slug) do nothing;`;
});
out.push("-- Campus map places (only places with a published source have coordinates)", ...placeSql);
for (const a of seed.seedAnnouncements) {
  out.push(`insert into public.announcements (edition_id, title, body, level, audience, pinned, published, published_at) select id, ${[a.title, a.body, a.level, a.audience, a.pinned, true, a.publishedAt].map(q).join(", ")} from _ed where not exists (select 1 from public.announcements x where x.edition_id = _ed.id and x.title = ${q(a.title)});`);
}
for (const [i, f] of seed.seedFaqs.entries()) {
  out.push(`insert into public.faqs (edition_id, question, answer, category, sort, published) select id, ${[f.question, f.answer, f.category, i, true].map(q).join(", ")} from _ed where not exists (select 1 from public.faqs x where x.edition_id = _ed.id and x.question = ${q(f.question)});`);
}
for (const [i, p] of seed.seedPartners.entries()) {
  out.push(`insert into public.partners (name, logo_url, url, relationship, published, sort) select ${[p.name, p.logoUrl, p.url, p.relationship, true, i].map(q).join(", ")} where not exists (select 1 from public.partners x where x.name = ${q(p.name)});`);
}
for (const [i, t] of seed.seedTimeline.entries()) {
  out.push(`insert into public.timeline_events (year, title, description, verified, published, sort) select ${[t.year, t.title, t.description, true, true, i].map(q).join(", ")} where not exists (select 1 from public.timeline_events x where x.title = ${q(t.title)});`);
}
for (const [i, r] of seed.seedResources.entries()) {
  out.push(`insert into public.resources (title, category, summary, url, is_example, published, sort) select ${[r.title, r.category, r.summary, r.url, r.isExample, true, i].map(q).join(", ")} where not exists (select 1 from public.resources x where x.title = ${q(r.title)});`);
}
out.push(
  `-- Default review rubric (editable in /admin)`,
  ...[
    ["Originality and relevance", "Is the question important and the work original?", 5],
    ["Methods", "Are the methods appropriate and clearly described?", 5],
    ["Results and conclusions", "Are the results clearly presented and conclusions supported?", 5],
    ["Clarity", "Is the abstract clearly written and well structured?", 5],
  ].map(([l, d, m], i) => `insert into public.review_criteria (edition_id, label, description, max_score, sort) select id, ${q(l)}, ${q(d)}, ${m}, ${i} from _ed where not exists (select 1 from public.review_criteria x where x.edition_id = _ed.id and x.label = ${q(l)});`),
  "commit;",
);

/**
 * Every statement must stand alone: the Supabase SQL editor may run statements on
 * different connections, so a temporary table would not survive between them.
 */
const standalone = (lines: string[]) =>
  lines.map((l) => l.replace(/\b(from|join|using) _ed\b/g, `$1 (select id from public.editions where year = ${e.year}) _ed`));

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), standalone(out).join("\n") + "\n");

/**
 * Update script for a database that was seeded before the confirmed
 * timetable, rooms and committee were added. Safe to run more than once.
 */
const update: string[] = [
  "-- Generated by scripts/generate-seed.ts. Brings an already-seeded database up to date with the",
  "-- confirmed timetable, rooms, committee and campus map. Safe to run more than once.",
  "begin;",
  "-- Campus map table (same as supabase/migrations/20261110010000_map_places.sql)",
  readFileSync(new URL("../supabase/migrations/20261110010000_map_places.sql", import.meta.url), "utf8").trim(),
  `update public.editions set start_time = ${q(e.startTime)}, end_time = ${q(e.endTime)} where year = ${e.year};`,
  "-- Remove the earlier untimed placeholder sessions (only ones nobody has scheduled).",
  "delete from public.sessions s using _ed where s.edition_id = _ed.id and s.starts_at is null and s.is_provisional;",
  ...seed.seedRooms.map(
    (r, i) =>
      `insert into public.rooms (edition_id, name, building, floor, directions, capacity, sort) select id, ${[r.name, r.building, r.floor, r.directions, r.capacity, i].map(q).join(", ")} from _ed where not exists (select 1 from public.rooms x where x.edition_id = _ed.id and x.name = ${q(r.name)});`,
  ),
  ...sessionSql,
  ...committeeSql,
  ...placeSql,
  "commit;",
];
writeFileSync(new URL("../supabase/updates/2026-11-10-programme-committee-map.sql", import.meta.url), standalone(update).join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
