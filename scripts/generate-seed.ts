/**
 * Generates supabase/seed.sql from src/content/seed.ts so the database starts
 * with exactly the same (verified or clearly provisional) content as the
 * fallback site. Run: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from "node:fs";
import * as seed from "../src/content/seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const e = seed.seedEdition;
const out: string[] = [
  "-- Generated by scripts/generate-seed.ts. Safe to run once on a fresh database.",
  "begin;",
  `insert into public.editions (year, slug, name, theme, theme_statement, event_date, start_time, end_time, timezone, venue_name, venue_institution, venue_address, venue_notes, expected_attendance, status, registration_url, registration_note, event_day_mode, post_event_mode, is_current, highlights, host_institution, poster_deadline, poster_requirements, abstract_config)
values (${[e.year, e.slug, e.name, e.theme, e.themeStatement, e.date, e.startTime, e.endTime, e.timezone, e.venueName, e.venueInstitution, e.venueAddress, e.venueNotes, e.expectedAttendance, e.status, e.registrationUrl, e.registrationNote, e.eventDayMode, e.postEventMode, true, e.highlights, e.hostInstitution, e.posterDeadline, e.posterRequirements, e.abstractConfig].map(q).join(", ")});`,
  `-- Helper: current edition id`,
  `create temporary table _ed as select id from public.editions where year = ${e.year};`,
];

for (const [i, r] of seed.seedRooms.entries()) {
  out.push(`insert into public.rooms (edition_id, name, building, floor, directions, capacity, sort) select id, ${[r.name, r.building, r.floor, r.directions, r.capacity, i].map(q).join(", ")} from _ed;`);
}
for (const w of seed.seedWorkshops) {
  out.push(
    `insert into public.workshops (edition_id, slug, number, title, strapline, summary, description, topics, outcomes, audience, facilitator, facilitator_bio, capacity, booking_enabled, accent, motif, notes) select id, ${[w.slug, w.number, w.title, w.strapline, w.summary, w.description, w.topics, w.outcomes, w.audience, w.facilitator, w.facilitatorBio, w.capacity, w.bookingEnabled, w.accent, w.motif, w.notes].map(q).join(", ")} from _ed;`,
  );
}
const firstRoom = seed.seedRooms[0]?.name;
for (const s of seed.seedSessions) {
  const room = s.roomId ? `(select id from public.rooms where name = ${q(firstRoom)} limit 1)` : "null";
  out.push(
    `insert into public.sessions (edition_id, slug, title, category, starts_at, ends_at, room_id, description, objectives, capacity, is_provisional, sort) select id, ${[s.slug, s.title, s.category, s.startsAt, s.endsAt].map(q).join(", ")}, ${room}, ${[s.description, s.objectives, s.capacity, s.isProvisional, s.sort].map(q).join(", ")} from _ed;`,
  );
}
for (const a of seed.seedAnnouncements) {
  out.push(`insert into public.announcements (edition_id, title, body, level, audience, pinned, published, published_at) select id, ${[a.title, a.body, a.level, a.audience, a.pinned, true, a.publishedAt].map(q).join(", ")} from _ed;`);
}
for (const [i, f] of seed.seedFaqs.entries()) {
  out.push(`insert into public.faqs (edition_id, question, answer, category, sort, published) select id, ${[f.question, f.answer, f.category, i, true].map(q).join(", ")} from _ed;`);
}
for (const [i, p] of seed.seedPartners.entries()) {
  out.push(`insert into public.partners (name, logo_url, url, relationship, published, sort) values (${[p.name, p.logoUrl, p.url, p.relationship, true, i].map(q).join(", ")});`);
}
for (const [i, t] of seed.seedTimeline.entries()) {
  out.push(`insert into public.timeline_events (year, title, description, verified, published, sort) values (${[t.year, t.title, t.description, true, true, i].map(q).join(", ")});`);
}
for (const [i, r] of seed.seedResources.entries()) {
  out.push(`insert into public.resources (title, category, summary, url, is_example, published, sort) values (${[r.title, r.category, r.summary, r.url, r.isExample, true, i].map(q).join(", ")});`);
}
out.push(
  `-- Default review rubric (editable in /admin)`,
  ...[
    ["Originality and relevance", "Is the question important and the work original?", 5],
    ["Methods", "Are the methods appropriate and clearly described?", 5],
    ["Results and conclusions", "Are the results clearly presented and conclusions supported?", 5],
    ["Clarity", "Is the abstract clearly written and well structured?", 5],
  ].map(([l, d, m], i) => `insert into public.review_criteria (edition_id, label, description, max_score, sort) select id, ${q(l)}, ${q(d)}, ${m}, ${i} from _ed;`),
  "drop table _ed;",
  "commit;",
);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`Wrote supabase/seed.sql (${out.length} statements)`);
